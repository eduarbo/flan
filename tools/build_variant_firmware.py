#!/usr/bin/env python3
"""Generate the ZMK shield and keymap of each Flan variant from design/variants.json.

Each variant keeps Flan36's electrical contract (col2row, the same nice!view SPI, the same
row 0-3 and column 0-5 pins) and adds only what its keys need: the outer pinky column uses
matrix column 0, already wired for thumb K30; the number row is matrix row 4, on the pin
recorded in design/pinmap.json under variants.<id>. The keymap is Flan36's, with the added
keys filled in per layer (KEYS below). Writes firmware/config/boards/shields/<id>/,
firmware/config/<id>.keymap and <id>.conf. A variant whose row-4 pin is not recorded yet
is skipped. Build with tools/build_firmware.sh <id>-left <id>-right <id>-right-no-display.
SPDX-License-Identifier: GPL-3.0-or-later
"""
from pathlib import Path
import json, re

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / "firmware/config"
HEADER = "// SPDX-License-Identifier: GPL-3.0-or-later\n// Generated by tools/build_variant_firmware.py from design/variants.json; edit the generator.\n"
PULL = "(GPIO_ACTIVE_HIGH | GPIO_PULL_DOWN)"
# Bindings for the added keys, per layer: outer column (left, right) on rows 0-2, then the
# number row (left K4c..., right) and its outer keys.
OUTER = {"base": [("&kp TAB", "&kp BSPC"), ("&kp LCTRL", "&kp SQT"), ("&kp LSHFT", "&kp ESC")],
         "numbers": [("&trans", "&trans")] * 3, "symbols": [("&trans", "&trans")] * 3, "settings": [("&none", "&none")] * 3}
NUMBER_ROW = {"base": ["&kp N1", "&kp N2", "&kp N3", "&kp N4", "&kp N5", "&kp N6", "&kp N7", "&kp N8", "&kp N9", "&kp N0"],
              "numbers": ["&kp F1", "&kp F2", "&kp F3", "&kp F4", "&kp F5", "&kp F6", "&kp F7", "&kp F8", "&kp F9", "&kp F10"],
              "symbols": ["&trans"] * 10, "settings": ["&none"] * 10}
NUMBER_OUTER = {"base": ("&kp GRAVE", "&kp MINUS"), "numbers": ("&kp F11", "&kp F12"),
                "symbols": ("&trans", "&trans"), "settings": ("&none", "&none")}

def gpios(pins, flags):
    return ", ".join(f"<&pro_micro {p} {flags}>" for p in pins)

def pins(pinmap, vid, side, number_row):
    base = pinmap["halves"][side]
    rows = list(base["rows"])
    if number_row:
        extra = pinmap.get("variants", {}).get(vid, {}).get(side, {}).get("row4")
        if extra is None:
            return None
        rows.append(extra)
    return rows, list(base["cols"])

def keymap(vid, spec):
    """Flan36's layers, with this variant's added keys in reading order."""
    text = (CONFIG / "flan36.keymap").read_text()
    out = text
    for layer in ("base", "numbers", "symbols", "settings"):
        m = re.search(rf"( {layer} {{ bindings = <\n)(.*?)(\n >; }};)", out, re.S)
        lines = m.group(2).split("\n")
        assert len(lines) == 4, layer
        fingers, thumbs = lines[:3], lines[3]
        if spec["outer_column"]:
            fingers = [f"  {OUTER[layer][i][0]} {line.strip()} {OUTER[layer][i][1]}" for i, line in enumerate(fingers)]
        if spec["number_row"]:
            row = NUMBER_ROW[layer]
            if spec["outer_column"]:
                row = [NUMBER_OUTER[layer][0], *row, NUMBER_OUTER[layer][1]]
            fingers = ["  " + " ".join(row)] + fingers
        out = out[:m.start(2)] + "\n".join(fingers + [thumbs]) + out[m.end(2):]
    return HEADER + out

def shield(vid, spec, transform, rows_l, cols_l, rows_r, cols_r):
    up = vid.upper()
    nrows = 5 if spec["number_row"] else 4
    files = {}
    files["Kconfig.shield"] = f"config SHIELD_{up}_LEFT\n def_bool $(shields_list_contains,{vid}_left)\nconfig SHIELD_{up}_RIGHT\n def_bool $(shields_list_contains,{vid}_right)\n"
    files["Kconfig.defconfig"] = (f"if SHIELD_{up}_LEFT\nconfig ZMK_KEYBOARD_NAME\n default \"{spec['title']}\"\nconfig ZMK_SPLIT_ROLE_CENTRAL\n default y\nendif\n"
                                  f"if SHIELD_{up}_LEFT || SHIELD_{up}_RIGHT\nconfig ZMK_SPLIT\n default y\nendif\n")
    rc = "\n".join("  " + line for line in transform)
    files[f"{vid}.dtsi"] = (HEADER + "#include <dt-bindings/zmk/matrix_transform.h>\n/ {\n"
        " chosen { zmk,kscan = &kscan0; zmk,matrix-transform = &default_transform; };\n"
        " default_transform: keymap_transform_0 {\n  compatible = \"zmk,matrix-transform\";\n"
        f"  columns = <12>; rows = <{nrows}>;\n  map = <\n{rc}\n  >;\n }};\n"
        " kscan0: kscan {\n  compatible = \"zmk,kscan-gpio-matrix\";\n  wakeup-source;\n  diode-direction = \"col2row\";\n"
        f"  row-gpios = {gpios(rows_l, PULL)};\n  col-gpios = {gpios(cols_l, 'GPIO_ACTIVE_HIGH')};\n }};\n}};\n")
    display = '#include "../flan36/flan36-display.dtsi"\n'
    files[f"{vid}_left.overlay"] = f'#include "{vid}.dtsi"\n' + display
    files[f"{vid}_right.overlay"] = (f'#include "{vid}.dtsi"\n' + display + "&default_transform { col-offset = <6>; };\n\n"
        "// Right-hand MCU pins exit toward the key field, as on Flan36.\n"
        f"&kscan0 {{\n row-gpios = {gpios(rows_r, PULL)};\n col-gpios = {gpios(cols_r, 'GPIO_ACTIVE_HIGH')};\n}};\n")
    return files

def main():
    variants = json.loads((ROOT / "design/variants.json").read_text())["variants"]
    pinmap = json.loads((ROOT / "design/pinmap.json").read_text())
    for vid, v in variants.items():
        if vid == "flan36":
            continue
        got = {s: pins(pinmap, vid, s, v["number_row"]) for s in ("left", "right")}
        if None in got.values():
            print(vid, "skipped: row-4 pin not recorded in design/pinmap.json")
            continue
        (rows_l, cols_l), (rows_r, cols_r) = got["left"], got["right"]
        for side, rows, cols in (("left", rows_l, cols_l), ("right", rows_r, cols_r)):
            used = [0, 1, 14, *rows, *cols]
            assert len(set(used)) == len(used), (vid, side, "pin used twice")
        d = CONFIG / "boards/shields" / vid
        d.mkdir(parents=True, exist_ok=True)
        for name, text in shield(vid, v, v["matrix"]["transform"], rows_l, cols_l, rows_r, cols_r).items():
            (d / name).write_text(text)
        (CONFIG / f"{vid}.keymap").write_text(keymap(vid, v))
        (CONFIG / f"{vid}.conf").write_text((CONFIG / "flan36.conf").read_text())
        print(vid, "shield, keymap and conf:", v["keys_total"], "keys")

if __name__ == "__main__":
    main()
